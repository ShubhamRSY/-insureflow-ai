"""Score SUB-057 through SUB-066. A null is never a correct answer.

Written before that hold-out exists. Do not edit this file to improve the score.
Synthetic only. Not a production approval.

Run: python underwriting_pipeline/ai/eval_holdout_057.py
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import prepare

ROOT = Path(__file__).resolve().parents[2]
INBOX = ROOT / "simulation" / "inbox"
GOLD = ROOT / "deliverables" / "senior-underwriter" / "gold-set"
OUT_MD = ROOT / "deliverables" / "ai-engineer" / "evals" / "SUB-057-066-holdout.md"
OUT_JSON = ROOT / "deliverables" / "ai-engineer" / "evals" / "SUB-057-066-holdout.json"
IDS = [f"SUB-{n:03d}" for n in range(57, 67)]
FIELDS = (
    "named_insured",
    "premises",
    "operations",
    "sales",
    "tiv",
    "construction",
    "year_built",
    "loss_runs",
    "conflict",
    "status",
)


def parse_gold(text: str) -> dict:
    out = {}
    for raw in text.splitlines():
        if not raw.startswith("- ") or ":" not in raw:
            continue
        key, val = raw[2:].split(":", 1)
        out[key.strip().lower()] = val.strip()
    return out


def digits(value: str) -> str:
    return "".join(ch for ch in value if ch.isdigit())


def words(text: str) -> list[str]:
    stop = {"with", "and", "the", "that", "this", "from", "unit"}
    return [w for w in re.findall(r"[a-z0-9]+", text.lower()) if w not in stop and (len(w) >= 4 or w.isdigit())]


def field_map(report: dict) -> dict:
    return {row["field_id"]: row for row in report["fields"]}


def judge(gold_missing: bool, got: str | None, matches: bool) -> str:
    """Null never counts as correct, including when the gold line says missing."""
    if not got:
        return "not_credited" if gold_missing else "miss"
    return "hit" if matches else "miss"


def score_one(sid: str) -> dict:
    gold = parse_gold((GOLD / f"{sid}.md").read_text())
    report = prepare.process_submission(INBOX / sid)
    got = field_map(report)
    named = got["named_insured"]["value"]
    premises = got["premises_address"]["value"]
    ops = got["operations"]["value"]
    sales = got["sales_or_payroll"]["value"]
    tiv = got["tiv_building"]["value"]
    construction = got["construction"]["value"]
    year = got["year_built"]["value"]
    runs = got["loss_run_valued_through"]["value"]
    identity = bool(named or premises or ops)
    open_conflicts = [c for c in report["conflicts"] if c.get("resolution") != "resolved"]
    conflict_blob = json.dumps(open_conflicts).lower()

    def has_all(needles: list[str]) -> bool:
        return bool(needles) and all(needle.lower() in conflict_blob for needle in needles)

    checks = {
        "named_insured": judge(False, named, named == gold["named insured"]),
        "operations": judge(False, ops, bool(ops) and all(word in set(words(ops)) for word in words(gold["operations"]))),
        "sales": judge(False, sales, bool(sales) and digits(sales) == digits(gold["sales"])),
        "construction": judge(False, construction, bool(construction) and gold["construction"].lower() in construction.lower()),
        "year_built": judge(False, year, bool(year) and digits(year) == digits(gold["year built"])),
    }
    if gold["premises"].lower().startswith("both"):
        needles = re.findall(r"\d+\s+[A-Za-z]+", gold["premises"])
        checks["premises"] = "hit" if has_all(needles) else "miss"
    else:
        checks["premises"] = judge(False, premises, premises == gold["premises"])
    if gold["tiv"].strip() == "0":
        checks["tiv"] = "hit" if tiv is not None and digits(tiv) in {"", "0"} else "miss"
    else:
        checks["tiv"] = judge(False, tiv, bool(tiv) and digits(tiv) == digits(gold["tiv"]))
    runs_missing = gold["loss runs"].lower().startswith("missing")
    date = re.search(r"20\d\d-\d\d-\d\d", gold["loss runs"])
    checks["loss_runs"] = judge(runs_missing, runs, bool(date) and bool(runs) and date.group(0) in runs)
    if gold["conflict"].lower() == "none":
        if not identity:
            checks["conflict"] = "not_credited"
        else:
            checks["conflict"] = "hit" if not open_conflicts else "miss"
    else:
        needles = [
            needle
            for needle in re.findall(r"\d+\s+[A-Za-z]+", gold["conflict"])
            if not needle.lower().endswith(" and")
        ] or re.findall(r"\d+", gold["conflict"])
        checks["conflict"] = "hit" if has_all(needles) else "miss"
    gold_complete = gold["status"].lower().startswith("complete")
    if not identity:
        checks["status"] = "miss" if gold_complete else "not_credited"
    else:
        checks["status"] = "hit" if report["complete"] is gold_complete else "miss"
    return {
        "submission": sid,
        "format": gold.get("format"),
        "error": report.get("error"),
        "checks": checks,
        "extracted_named_insured": named,
    }


def main() -> None:
    rows = [score_one(sid) for sid in IDS]
    counted = {field: {"hit": 0, "miss": 0, "not_credited": 0} for field in FIELDS}
    for row in rows:
        for field, mark in row["checks"].items():
            counted[field][mark] += 1
    OUT_JSON.write_text(json.dumps({"submissions": rows, "counted": counted}, indent=2) + "\n")
    lines = [
        "# Hold-out extraction score — SUB-057 through SUB-066",
        "",
        "- Author: @ai-engineer",
        "- Scored by @model-risk with this file unchanged after the gold answers were written.",
        "- A null that matches a missing gold line is not_credited. It is not a correct answer.",
        "- Synthetic. Not a production approval.",
        "",
        "## Per-field",
        "",
        "| Field | Hit | Miss | Not credited |",
        "|---|---|---|---|",
    ]
    for field in FIELDS:
        item = counted[field]
        lines.append(f"| {field} | {item['hit']} | {item['miss']} | {item['not_credited']} |")
    lines.append("")
    lines.append("## Per submission")
    lines.append("")
    for row in rows:
        missed = [name for name, mark in row["checks"].items() if mark == "miss"]
        lines.append(
            f"- {row['submission']} ({row['format']}): extracted name {row['extracted_named_insured'] or 'null'}. "
            f"Misses: {', '.join(missed) or 'none'}. "
            f"Call: {row['error'] or 'ok'}."
        )
    lines.append("")
    OUT_MD.write_text("\n".join(lines))
    print(OUT_MD)
    for field in FIELDS:
        item = counted[field]
        print(field, item)


if __name__ == "__main__":
    main()
